-- Tarifa de IVA configurable por el dueño. Se guarda un historial: cada tarifa
-- rige desde su fecha hasta que otra posterior la reemplaza, así un cambio de
-- ley se puede registrar con anticipación.
CREATE TABLE tarifa_iva (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    porcentaje     NUMERIC(5, 2) NOT NULL,
    vigente_desde  DATE NOT NULL,
    registrada_en  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_tarifa_iva_vigente_desde UNIQUE (vigente_desde),
    CONSTRAINT ck_tarifa_iva_porcentaje CHECK (porcentaje >= 0 AND porcentaje < 100)
);

