-- Marcas escritas a mano en vehiculos existentes que no estan en el catalogo.
INSERT INTO marca (nombre)
SELECT MIN(TRIM(marca))
FROM vehiculo
WHERE marca IS NOT NULL AND TRIM(marca) <> ''
GROUP BY UPPER(TRIM(marca))
HAVING UPPER(TRIM(marca)) NOT IN (SELECT UPPER(nombre) FROM marca);

ALTER TABLE vehiculo ADD COLUMN marca_id BIGINT;

UPDATE vehiculo v
SET marca_id = m.id
FROM marca m
WHERE UPPER(m.nombre) = UPPER(TRIM(v.marca));

ALTER TABLE vehiculo DROP COLUMN marca;

ALTER TABLE vehiculo
    ADD CONSTRAINT fk_vehiculo_marca FOREIGN KEY (marca_id) REFERENCES marca (id);
