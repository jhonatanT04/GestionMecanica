CREATE TABLE marca (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    activa BOOLEAN NOT NULL DEFAULT TRUE
);

-- Unicidad sin distinguir mayusculas: "Toyota" y "TOYOTA" son la misma marca.
CREATE UNIQUE INDEX uk_marca_nombre ON marca (UPPER(nombre));

